def triangular_lr(epoch, total_epochs=300, min_lr=0.001, max_lr=0.1):

    half = total_epochs // 2

    if epoch <= half:
        return min_lr + (max_lr-min_lr) * epoch/half
    else:
        return max_lr - (max_lr-min_lr)*(epoch-half)/half

