def train_linear_regression(X_train, y_train, X_test, y_test, learning_rate=0.05, epochs=300, verbose=True):
  n_features = X_train.shape[1]
  w = np.zeros(n_features)

  train_mses = []
  test_mses = []

  for epoch in range(epochs):
      grads = compute_gradients(X_train, y_train, w)
      w = gradient_descent_step(w, grads, learning_rate)

      train_mse = mse_loss(X_train, y_train, w)
      test_mse = mse_loss(X_test, y_test, w)
      train_mses.append(train_mse)
      test_mses.append(test_mse)

      if verbose and epoch % 50 == 0:
          print(f"Epoch {epoch:3d}: Train MSE = {train_mse:8.2f}, Test MSE = {test_mse:8.2f}")

  return w, train_mses, test_mses

