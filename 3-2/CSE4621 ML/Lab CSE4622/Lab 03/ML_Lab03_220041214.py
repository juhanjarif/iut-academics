def compute_gradients(X, y, w):
  n = X.shape[0]
  d = len(w)
  gradients = np.zeros(d)

  predictions = predict(X, w)

  for j in range(d):
    gradient_sum = 0.0
    for i in range(n):
      gradient_sum += (predictions[i] - y[i]) * X[i][j]
    gradients[j] = ((2 * gradient_sum) / n)

  return gradients

def gradient_descent_step(w, grads, lr):
  w_new = w.copy()
  for i in range(len(w)):
    w_new[i] = w[i] - lr * grads[i]
  return w_new

