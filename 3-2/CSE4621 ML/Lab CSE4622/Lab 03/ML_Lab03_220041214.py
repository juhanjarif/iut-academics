def compute_gradients_l2(X, y, w, lambda_reg):
    n = X.shape[0]
    d = len(w)
    predictions = predict(X, w)
    gradients = np.zeros(d)

    for j in range(d):
        grad_sum = 0.0
        for i in range(n):
            error = predictions[i] - y[i]
            grad_sum += error * X[i][j]
        gradients[j] = (2 / n) * grad_sum

        if j > 0:
            gradients[j] += (2 * lambda_reg / n) * w[j]

    return gradients

def sign(x):
    if x > 0:
        return 1
    elif x < 0:
        return -1
    else:
        return 0

def compute_gradients_l1(X, y, w, lambda_reg):
    n = X.shape[0]
    d = len(w)
    predictions = predict(X, w)
    gradients = np.zeros(d)

    for j in range(d):
        grad_sum = 0.0
        for i in range(n):
            error = predictions[i] - y[i]
            grad_sum += error * X[i][j]
        gradients[j] = (2 / n) * grad_sum
        if j > 0:
            gradients[j] += (lambda_reg / n) * sign(w[j])

    return gradients

