def mse_loss_l2(X, y, w, lambda_reg):
    n = X.shape[0]
    predictions = predict(X, w)

    mse = 0.0
    for i in range(n):
        error = predictions[i] - y[i]
        mse += error * error
    mse = mse / n

    penalty = 0.0
    for j in range(1, len(w)):
        penalty += w[j] ** 2
    penalty = (lambda_reg / n) * penalty

    return mse + penalty

def mse_loss_l1(X, y, w, lambda_reg):
    n = X.shape[0]
    predictions = predict(X, w)
    mse = 0.0

    for i in range(n):
        error = predictions[i] - y[i]
        mse += error * error
    mse = mse / n

    penalty = 0.0
    for j in range(1, len(w)):
        penalty += abs(w[j])

    penalty = (lambda_reg / n) * penalty

    return mse + penalty

