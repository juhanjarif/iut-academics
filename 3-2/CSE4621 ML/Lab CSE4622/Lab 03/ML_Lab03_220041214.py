# hypothesis functions
def predict_single(x, w):
  prediction = 0.0

  for i in range(len(x)):
    prediction += x[i] * w[i]

  return prediction

def predict(X, w):
  predictions = []

  for i in range(len(X)):
    predictions.append(predict_single(X[i], w))

  return np.array(predictions)

