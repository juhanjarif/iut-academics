# mse loss
def mse_loss(X, y, w):
  size = len(X)
  total_squared_error = 0.0

  for i in range(size):
    y_pred = predict_single(X[i], w)

    error = y_pred - y[i]

    total_squared_error += (error * error)
  return (total_squared_error / size)

