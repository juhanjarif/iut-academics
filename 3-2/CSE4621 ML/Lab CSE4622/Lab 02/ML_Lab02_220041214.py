# most outliers
for pclass in df['Pclass'].unique():

    class_data = df[df['Pclass'] == pclass]['Fare']

    Q1 = class_data.quantile(0.25)
    Q3 = class_data.quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outliers = class_data[(class_data < lower_bound) | (class_data > upper_bound)]

    print(f"\nClass {pclass}")
    print(f"Q1 = {Q1:.2f}, Q3 = {Q3:.2f}, IQR = {IQR:.2f}")
    print(f"Lower bound: {lower_bound:.2f}, Upper bound: {upper_bound:.2f}")
    print(f"Number of outliers in Fare: {len(outliers)}")

# class with the highest median fare
median_fares = df.groupby('Pclass')['Fare'].median()

